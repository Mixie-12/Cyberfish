def reply(query: bytes, records: list[tuple[int, bytes]], rcode: int = 0) -> bytes:
    """A resolver's answer to query with (type, address bytes) records,
    each owned by the question name through a compression pointer."""
    query_id = struct.unpack("!H", query[:2])[0]
    header = struct.pack("!HHHHHH", query_id, 0x8180 | rcode, 1, len(records), 0, 0)
    answer_records = b"".join(
        struct.pack("!HHHIH", 0xC00C, kind, 1, 300, len(data)) + data for kind, data in records
    )
    return header + query[12:] + answer_records


def test_answers_are_read_by_type_and_checked_against_the_query() -> None:
    query = dns_query("dns.google", 0x1234, DNS_A, dns_check.RECURSION_DESIRED)
    message = reply(
        query,
        [
            (DNS_A, bytes([8, 8, 8, 8])),
            (DNS_A, bytes([8, 8, 4, 4])),
            (DNS_AAAA, socket.inet_pton(socket.AF_INET6, "2001:4860:4860::8888")),
            # An A record of the wrong length is skipped.
            (DNS_A, bytes([1, 2, 3])),
        ],
    )
    assert answers(message, 0x1234, DNS_A) == {"8.8.8.8", "8.8.4.4"}
    assert answers(message, 0x1234, DNS_AAAA) == {"2001:4860:4860::8888"}
    assert answers(message, 0x1235, DNS_A) is None, "another query's answer"
    assert answers(query, 0x1234, DNS_A) is None, "a question is not an answer"
    assert answers(reply(query, [], rcode=3), 0x1234, DNS_A) == frozenset(), "no such name"
    assert answers(reply(query, [], rcode=2), 0x1234, DNS_A) is None, "server failure"
    assert answers(message[:-6], 0x1234, DNS_A) is None, "cut short"
    assert answers(b"\x12\x34", 0x1234, DNS_A) is None


def test_the_resolver_is_the_first_ipv4_name_server(tmp_path: Path) -> None:
    resolv = tmp_path / "resolv.conf"
    resolv.write_text(
        "# Generated by NetworkManager\nsearch home\nnameserver fe80::1%eth0\n"
        "nameserver 192.168.1.1\nnameserver 1.1.1.1\n"
    )
    assert lan_resolver(resolv) == "192.168.1.1"
    resolv.write_text("nameserver not-an-address\n")
    assert lan_resolver(resolv) is None
    assert lan_resolver(tmp_path / "missing") is None


def test_only_answers_that_lead_somewhere_are_compared() -> None:
    one = frozenset({"1.1.1.1", "1.0.0.1"})
    google = frozenset({"8.8.8.8"})
    root = frozenset({"198.41.0.4"})
    elsewhere = frozenset({"203.0.113.66"})
    blocked = frozenset({"0.0.0.0"})  # noqa: S104 - an answer, not a bind address

    assert conclude([("one", one, one), ("google", google, google), ("root", root, root)]) == OK
    assert (
        conclude([("one", elsewhere, one), ("google", elsewhere, google), ("root", root, root)])
        == MISMATCH
    )
    # One name may move or be filtered without the network being hijacked.
    assert conclude([("one", elsewhere, one), ("google", google, google)]) == OK
    assert conclude([("one", blocked, one), ("google", blocked, google)]) == UNAVAILABLE
    assert conclude([("one", frozenset(), one), ("google", None, google)]) == UNAVAILABLE
    assert conclude([("one", one, None), ("google", google, None)]) == UNAVAILABLE


def test_a_mismatch_is_reported_after_two_checks_in_a_row(monkeypatch: pytest.MonkeyPatch) -> None:
    independent = frozenset({"192.0.2.1"})
    local = {"answer": independent}
    monkeypatch.setattr(dns_check, "ask_lan", lambda resolver, name, record_type: local["answer"])
    monkeypatch.setattr(dns_check, "ask_doh", lambda questions: [independent] * len(questions))
    integrity = Integrity()

    assert integrity.check("192.168.1.1") == OK
    local["answer"] = frozenset({"203.0.113.66"})
    assert integrity.check("192.168.1.1") is None, "one check is not enough"
    assert integrity.check("192.168.1.1") == MISMATCH
    assert integrity.check("192.168.1.1") == MISMATCH
    local["answer"] = independent
    assert integrity.check("192.168.1.1") == OK
    local["answer"] = frozenset({"203.0.113.66"})
    assert integrity.check("192.168.1.1") is None, "the count starts again"


def test_the_resolver_is_asked_over_udp_and_strangers_are_ignored(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    server = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    server.bind(("127.0.0.1", 0))
    monkeypatch.setattr(dns_check, "DNS_PORT", server.getsockname()[1])

    def answer() -> None:
        query, client = server.recvfrom(512)
        assert query[2:4] == b"\x01\x00", "recursion desired"
        wrong_id = bytes([query[0] ^ 0xFF]) + query[1:]
        server.sendto(reply(wrong_id, [(DNS_A, bytes([6, 6, 6, 6]))]), client)
        server.sendto(reply(query, [(DNS_A, bytes([192, 0, 2, 7]))]), client)

    thread = threading.Thread(target=answer)
    thread.start()
    try:
        assert ask_lan("127.0.0.1", "example.org", DNS_A) == {"192.0.2.7"}
    finally:
        thread.join()
        server.close()


def test_a_silent_resolver_is_no_answer(monkeypatch: pytest.MonkeyPatch) -> None:
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as server:
        server.bind(("127.0.0.1", 0))
        monkeypatch.setattr(dns_check, "DNS_PORT", server.getsockname()[1])
        assert ask_lan("127.0.0.1", "example.org", DNS_A, timeout=0.2) is None


class FakeResponse:
    def __init__(self, status: int, body: bytes) -> None:
        self.status = status
        self.body = body

    def read(self, limit: int) -> bytes:
        return self.body[:limit]


class FakeHttps:
    """Answers DNS over HTTPS questions from outcomes: (status, records) or an error."""

    outcomes: ClassVar[list[tuple[int, list[tuple[int, bytes]]] | OSError]] = []
    instances: ClassVar[list["FakeHttps"]] = []

    def __init__(self, host: str, timeout: float, context: object) -> None:
        self.host = host
        self.requests: list[tuple[str, str, bytes, dict]] = []
        self.closed = False
        FakeHttps.instances.append(self)

    def request(self, method: str, path: str, body: bytes, headers: dict) -> None:
        self.requests.append((method, path, body, headers))

    def getresponse(self) -> FakeResponse:
        outcome = FakeHttps.outcomes.pop(0)
        if isinstance(outcome, OSError):
            raise outcome
        status, records = outcome
        return FakeResponse(status, reply(self.requests[-1][2], records))

    def close(self) -> None:
        self.closed = True


def test_dns_over_https_asks_the_fixed_provider_and_stops_at_a_failure(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    monkeypatch.setattr(dns_check.http.client, "HTTPSConnection", FakeHttps)
    monkeypatch.setattr(FakeHttps, "instances", [])
    monkeypatch.setattr(
        FakeHttps, "outcomes", [(200, [(DNS_A, bytes([1, 1, 1, 1]))]), (503, []), (200, [])]
    )

    found = dns_check.ask_doh([("one.one.one.one", DNS_A), ("dns.google", DNS_A), ("x", DNS_A)])

    assert found == [frozenset({"1.1.1.1"}), None, None]
    (connection,) = FakeHttps.instances
    assert connection.host == "1.1.1.1"
    assert connection.closed
    method, path, _, headers = connection.requests[0]
    assert (method, path) == ("POST", "/dns-query")
    assert headers["Content-Type"] == "application/dns-message"
    assert len(connection.requests) == 2, "nothing more is asked after a failure"

    monkeypatch.setattr(FakeHttps, "outcomes", [OSError("certificate verify failed")])
    assert dns_check.ask_doh([("dns.google", DNS_A), ("dns.google", DNS_AAAA)]) == [None, None]
